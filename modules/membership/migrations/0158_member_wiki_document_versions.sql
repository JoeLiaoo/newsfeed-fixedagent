CREATE TABLE member_wiki_document_versions (
  id text PRIMARY KEY,
  document_id text NOT NULL REFERENCES member_wiki_documents(id),
  version_no int NOT NULL,
  uploader_id text NOT NULL REFERENCES member_users(id),
  file_name text NOT NULL,
  media_type text NOT NULL,
  format text NOT NULL CHECK (format IN ('pdf', 'docx', 'pptx', 'markdown')),
  byte_size int NOT NULL,
  sha256 text NOT NULL,
  body bytea NOT NULL,
  source_title text,
  source_author text,
  source_org text,
  source_date date,
  source_kind text,
  extracted_text text,
  extraction_status text NOT NULL DEFAULT 'pending' CHECK (extraction_status IN ('pending', 'available', 'unavailable')),
  extraction_note text,
  superseded_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (document_id, version_no),
  UNIQUE (document_id, sha256)
);
